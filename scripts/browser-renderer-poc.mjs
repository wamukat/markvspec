import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { gzipSync } from "node:zlib";

const root = dirname(fileURLToPath(new URL("../package.json", import.meta.url)));
const workDir = join(root, ".work", "browser-renderer-poc");
const exampleSourcePath = join(root, "examples", "01-basics", "hello-screen.vspec.md");
const browserEntry = join(root, "packages", "core", "dist", "browser.js");
const bundlePath = join(workDir, "markvspec-browser.js");
const metafilePath = join(workDir, "metafile.json");
const exampleDir = join(workDir, "examples");
const copiedExamplePath = join(exampleDir, basename(exampleSourcePath));
const htmlPath = join(workDir, "index.html");
const reportPath = join(workDir, "report.md");

function run(command, args) {
  execFileSync(command, args, { cwd: root, stdio: "inherit" });
}

function posix(path) {
  return path.split(/[\\/]/u).join("/");
}

function formatKiB(bytes) {
  return `${(bytes / 1024).toFixed(1)} KiB`;
}

rmSync(workDir, { recursive: true, force: true });
mkdirSync(exampleDir, { recursive: true });

run("npm", ["run", "build", "-w", "@markvspec/core"]);
copyFileSync(exampleSourcePath, copiedExamplePath);
run("node_modules/.bin/esbuild", [
  browserEntry,
  "--bundle",
  "--format=esm",
  "--platform=browser",
  "--minify",
  `--outfile=${bundlePath}`,
  `--metafile=${metafilePath}`
]);

const source = readFileSync(exampleSourcePath, "utf8");
const browserModule = await import(pathToFileURL(browserEntry).href);
const result = browserModule.parseMarkVSpec(source);
const html = browserModule.renderMarkVSpecHtml(result, { showIds: true });

if (!html.includes("mm-wireframe")) {
  throw new Error("Browser bundle smoke failed: rendered HTML does not include mm-wireframe.");
}
if (!Array.isArray(result.diagnostics)) {
  throw new Error("Browser bundle smoke failed: parse result diagnostics is not an array.");
}

writeFileSync(htmlPath, `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>MarkVSpec Browser Renderer PoC</title>
    <style>
      body { font-family: system-ui, sans-serif; margin: 0; padding: 24px; }
      main { display: grid; gap: 16px; grid-template-columns: minmax(0, 1fr) minmax(0, 1fr); }
      pre { background: #111827; color: #f8fafc; margin: 0; overflow: auto; padding: 12px; }
      @media (max-width: 900px) { main { grid-template-columns: 1fr; } }
    </style>
  </head>
  <body>
    <h1>MarkVSpec Browser Renderer PoC</h1>
    <main>
      <section>
        <h2>Source</h2>
        <pre id="source"></pre>
      </section>
      <section>
        <h2>Rendered Preview</h2>
        <div id="preview"></div>
        <h2>Diagnostics</h2>
        <pre id="diagnostics"></pre>
      </section>
    </main>
    <script type="module">
      import { parseMarkVSpec, renderMarkVSpecHtml } from "./markvspec-browser.js";

      const response = await fetch("./examples/${basename(exampleSourcePath)}");
      const source = await response.text();
      const result = parseMarkVSpec(source);

      document.querySelector("#source").textContent = source;
      document.querySelector("#preview").innerHTML = renderMarkVSpecHtml(result, { showIds: true });
      document.querySelector("#diagnostics").textContent = JSON.stringify(result.diagnostics, null, 2);
    </script>
  </body>
</html>
`);

const bundle = readFileSync(bundlePath);
const metafile = JSON.parse(readFileSync(metafilePath, "utf8"));
const nodeInputs = Object.keys(metafile.inputs).filter((input) => input.startsWith("node:") || input.includes("/node:"));
const report = `# Browser Renderer PoC

Generated by \`scripts/browser-renderer-poc.mjs\`.

## Result

- Browser bundle: possible through \`packages/core/dist/browser.js\`.
- Root package entry is still not treated as browser-safe for this PoC because Node-only renderer message file loading remains on the root API surface.
- PoC output is under \`.work/browser-renderer-poc/\` and is not referenced by docs-site or Pages.

## Artifacts

- Bundle: \`${posix(relative(root, bundlePath))}\`
- HTML PoC: \`${posix(relative(root, htmlPath))}\`
- Source fetched by PoC: \`${posix(relative(root, copiedExamplePath))}\`
- Metafile: \`${posix(relative(root, metafilePath))}\`

## Metrics

- Bundle size: ${formatKiB(bundle.byteLength)}
- Gzip size: ${formatKiB(gzipSync(bundle).byteLength)}
- Diagnostics for \`${posix(relative(root, exampleSourcePath))}\`: ${result.diagnostics.length}
- Node built-in inputs in browser bundle: ${nodeInputs.length}

## Runtime Constraints

- docs-site must publish source \`.vspec.md\` files or an equivalent source endpoint before a read-only dynamic preview can fetch real examples.
- Existing generated HTML should remain the fallback for fetch, parse, render, or JavaScript-disabled failures.
- Worker execution is not required for the small smoke example, but should be measured with larger examples before enabling dynamic rendering by default.
- Renderer message overrides that require filesystem lookup must stay out of the browser entry; browser callers should pass explicit messages or use built-in locale messages.
- The script smoke-tests the browser entry API in Node and emits a browser HTML fixture for manual fetch/render verification.
`;

writeFileSync(reportPath, report);

console.log(report);
